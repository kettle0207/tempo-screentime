// Release helper: creates the update signing key and the signed tempo-update.txt for GitHub Releases.
//   keygen <private-key.xml>                 create a new RSA-3072 key and rewrite src/Core/UpdateKey.cs
//   sign <private-key.xml> <installer.exe> <version> <notes.txt> <out-dir> [minimum]
//   verify <tempo-update.txt> <installer.exe>
using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using Tempo;

static int Fail(string message) { Console.Error.WriteLine(message); return 2; }
var root = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "../../../../.."));
if (args.Length == 0) return Fail("usage: keygen | sign | verify");
switch (args[0])
{
    case "keygen" when args.Length >= 2:
    {
        if (File.Exists(args[1])) return Fail("refusing to overwrite " + args[1]);
        using var rsa = RSA.Create(3072);
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(args[1]))!);
        File.WriteAllText(args[1], rsa.ToXmlString(true));
        var p = rsa.ExportParameters(false);
        var keyFile = args.Length >= 3 ? args[2] : Path.Combine(root, "src/Core/UpdateKey.cs");
        var repo = File.Exists(keyFile) ? System.Text.RegularExpressions.Regex.Match(File.ReadAllText(keyFile), "Repository = \"([^\"]+)\"").Groups[1].Value : "";
        if (repo.Length == 0) repo = "OWNER/Tempo";
        File.WriteAllText(keyFile, $$"""
            namespace Tempo
            {
                // Generated by tools/Release keygen. Only the public half of the update signing key is embedded.
                internal static class UpdateKey
                {
                    internal const string Repository = "{{repo}}";
                    internal const string Modulus = "{{Convert.ToBase64String(p.Modulus!)}}";
                    internal const string Exponent = "{{Convert.ToBase64String(p.Exponent!)}}";
                }
            }

            """);
        Console.WriteLine("private key: " + Path.GetFullPath(args[1]));
        Console.WriteLine("public key written to " + keyFile);
        return 0;
    }
    case "sign" when args.Length >= 6:
    {
        using var rsa = RSA.Create();
        rsa.FromXmlString(File.ReadAllText(args[1]));
        var installer = args[2]; var version = args[3];
        if (!UpdateManifest.TryVersion(version, out _)) return Fail("version must be X.Y.Z");
        byte[] bytes = File.ReadAllBytes(installer);
        var notes = File.ReadAllText(args[4], Encoding.UTF8).Replace("\r\n", "\n").Trim();
        var body = new StringBuilder();
        body.Append("format=").Append(UpdateManifest.Format).Append('\n');
        body.Append("version=").Append(version).Append('\n');
        body.Append("file=").Append(Path.GetFileName(installer)).Append('\n');
        body.Append("size=").Append(bytes.Length.ToString(CultureInfo.InvariantCulture)).Append('\n');
        body.Append("sha256=").Append(UpdateClient.Hex(SHA256.HashData(bytes))).Append('\n');
        body.Append("date=").Append(DateTime.Now.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture)).Append('\n');
        if (args.Length >= 7) body.Append("minimum=").Append(args[6]).Append('\n');
        body.Append('\n').Append(notes).Append('\n');
        var data = new UTF8Encoding(false).GetBytes(body.ToString());
        var sig = rsa.SignData(data, HashAlgorithmName.SHA256, RSASignaturePadding.Pss);
        Directory.CreateDirectory(args[5]);
        var output = Path.Combine(args[5], UpdateManifest.Name);
        File.WriteAllBytes(output, Encoding.ASCII.GetBytes(Convert.ToBase64String(sig) + "\n").Concat(data).ToArray());
        // Self-check against the key embedded in the shipped dashboard.
        var info = UpdateManifest.Parse(File.ReadAllBytes(output), UpdateManifest.PublicKey);
        Console.WriteLine($"signed {output}: {info.version} {info.file} {info.size} bytes sha256={info.sha256}");
        return 0;
    }
    case "verify" when args.Length >= 3:
    {
        var info = UpdateManifest.Parse(File.ReadAllBytes(args[1]), UpdateManifest.PublicKey);
        var hash = UpdateClient.Hex(SHA256.HashData(File.ReadAllBytes(args[2])));
        if (hash != info.sha256 || new FileInfo(args[2]).Length != info.size) return Fail("installer does not match manifest");
        Console.WriteLine($"OK {info.version} {info.file}");
        return 0;
    }
}
return Fail("usage: keygen | sign | verify");
